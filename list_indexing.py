
# Python List - Indexing

fruits = ["Apple", "Banana", "Mango", "Orange", "Grapes"]

# Positive Indexing

print(fruits[0])
print(fruits[1])
print(fruits[2])

# Negative Indexing

print(fruits[-1])
print(fruits[-2])
print(fruits[-3])

# Store value in a variable

first_fruit = fruits[0]
print(first_fruit)

last_fruit = fruits[-1]
print(last_fruit)