
# Python List - Nested List

students = [
    ["Naina", 20],
    ["Rahul", 22],
    ["Priya", 21]
]

print(students)

# Access complete list

print(students[0])
print(students[1])

# Access individual values

print(students[0][0])
print(students[0][1])

print(students[2][0])
print(students[2][1])