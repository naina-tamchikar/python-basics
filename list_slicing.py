
# Python List - Slicing

fruits = ["Apple", "Banana", "Mango", "Orange", "Grapes", "Kiwi"]

# Slice from index 1 to 3

print(fruits[1:4])

# Slice from beginning

print(fruits[:3])

# Slice till the end

print(fruits[2:])

# Last three items

print(fruits[-3:])

# Slice using negative index

print(fruits[-5:-2])

# Copy the complete list

print(fruits[:])