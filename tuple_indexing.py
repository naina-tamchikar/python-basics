
# Tuple Indexing

fruits = ("Apple", "Banana", "Mango", "Orange", "Grapes")

# Positive Indexing
print("First Fruit:", fruits[0])
print("Second Fruit:", fruits[1])
print("Last Fruit:", fruits[4])

# Negative Indexing
print("Last Fruit:", fruits[-1])
print("Second Last Fruit:", fruits[-2])
print("Third Last Fruit:", fruits[-3])

# Accessing Different Elements
print("Middle Fruit:", fruits[2])